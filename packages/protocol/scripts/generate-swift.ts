import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import * as z from "zod/mini";

/**
 * Generates Swift `Codable` types from the committed JSON Schemas (plan 3.2.3).
 *
 * quicktype names a repeated object after one of its properties, and it does not merge copies that
 * live in different places. Window totals are rewritten to one `$ref` before quicktype runs, and
 * objects whose Swift name would otherwise be unstable (`Error`, `PurpleSync`, `Last30D`) get a
 * JSON Schema `title`. Both transforms are derived from `schema/*.json`; the committed schemas stay
 * the zod export. Dates stay strings so a plain `JSONDecoder` accepts the fixtures.
 */

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(packageRoot, "..", "..");
const schemaDir = join(packageRoot, "schema");
const outputPath = join(repoRoot, "apps/macos/SnorlaxKit/Sources/SnorlaxKit/Generated/Protocol.swift");

const jsonValue = z.json();
type Json = z.output<typeof jsonValue>;
const jsonObjectSchema = z.record(z.string(), jsonValue);
type JsonObject = z.output<typeof jsonObjectSchema>;

const windowKeys = [
  "cacheReadTokens",
  "costUsd",
  "inputTokens",
  "outputTokens",
  "requests",
  "sessions",
  "tokens",
  "unpricedRequests"
];

/** Titles keyed by schema file name, then by the `/`-joined path of the object. */
const titles: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  failure: { "properties/error": "FailureError" },
  snapshot: {
    "properties/status": "SnapshotStatus",
    "properties/status/properties/sync": "SnapshotSync"
  },
  status: { "properties/sync": "StatusSync" },
  "refresh-result": { "properties/sync": "RefreshSync" }
};

const asObject = (value: Json): JsonObject | undefined => {
  if (Array.isArray(value)) {
    return undefined;
  }
  const parsed = z.safeParse(jsonObjectSchema, value);
  if (!parsed.success) {
    return undefined;
  }
  return parsed.data;
};

const isWindowTotal = (value: JsonObject): boolean => {
  if (value.type !== "object") {
    return false;
  }
  const rawProperties = value.properties;
  if (rawProperties === undefined) {
    return false;
  }
  const properties = asObject(rawProperties);
  if (properties === undefined) {
    return false;
  }
  const keys = Object.keys(properties).sort();
  return keys.length === windowKeys.length && windowKeys.every((key, index) => key === keys[index]);
};

const withTitle = (node: JsonObject, fileName: string, path: readonly string[]): JsonObject => {
  const fromTable = titles[fileName]?.[path.join("/")];
  const title = path.at(-1) === "state" && Array.isArray(node.enum) ? "SyncState" : fromTable;
  if (title === undefined || node.title !== undefined) {
    return node;
  }
  return { ...node, title };
};

/**
 * Shares window totals through `$ref` and stamps titles. The rest of the document is unchanged,
 * so quicktype still sees the committed field set.
 */
const prepareSchema = (document: Json, fileName: string): Json => {
  let windowTotal: JsonObject | undefined;
  const walk = (node: Json, path: readonly string[]): Json => {
    if (Array.isArray(node)) {
      return node.map((item, index) => walk(item, [...path, String(index)]));
    }
    const object = asObject(node);
    if (object === undefined) {
      return node;
    }
    if (isWindowTotal(object)) {
      windowTotal ??= object;
      return { $ref: "#/$defs/WindowTotal" };
    }
    const next: JsonObject = {};
    for (const [key, value] of Object.entries(object)) {
      next[key] = walk(value, [...path, key]);
    }
    return withTitle(next, fileName, path);
  };
  const transformed = walk(document, []);
  if (windowTotal === undefined) {
    return transformed;
  }
  const root = asObject(transformed);
  if (root === undefined) {
    return transformed;
  }
  return { ...root, $defs: { WindowTotal: { ...windowTotal, title: "WindowTotal" } } };
};

const readSchema = (fileName: string): Json => {
  const parsed: unknown = JSON.parse(readFileSync(join(schemaDir, fileName), "utf8"));
  return z.parse(jsonValue, parsed);
};

const header = `// Generated by packages/protocol/scripts/generate-swift.ts from packages/protocol/schema.
// Do not edit. Change the JSON Schemas and run \`pnpm --filter @rivus/snorlax-protocol run generate:swift\`.
`;

const hashableNote =
  "\n//\n// Hashable or Equatable:\n// The compiler will not be able to synthesize the implementation of Hashable or Equatable\n// for types that require the use of JSONAny, nor will the implementation of Hashable be\n// synthesized for types that have collections (such as arrays or dictionaries).\n";

const finishSwift = (generated: string): string => {
  const foundation = generated.indexOf("import Foundation");
  if (foundation < 0) {
    throw new Error("quicktype output has no Foundation import");
  }
  const body = generated
    .slice(foundation)
    .replaceAll(hashableNote, "\n")
    .replace(/\n{3,}/g, "\n\n");
  return `${header}\n${body.trimEnd()}\n`;
};

const schemaFiles = readdirSync(schemaDir)
  .filter((name) => name.endsWith(".json"))
  .sort();
if (schemaFiles.length === 0) {
  throw new Error(`no JSON Schemas in ${schemaDir}`);
}

const tempDir = mkdtempSync(join(tmpdir(), "snorlax-swift-"));
try {
  const sources: string[] = [];
  for (const fileName of schemaFiles) {
    const prepared = prepareSchema(readSchema(fileName), fileName.replace(/\.json$/, ""));
    const source = join(tempDir, fileName);
    writeFileSync(source, JSON.stringify(prepared));
    sources.push(source);
  }
  const quicktype = join(packageRoot, "node_modules/.bin/quicktype");
  const result = spawnSync(
    quicktype,
    [
      "--src-lang",
      "schema",
      "--lang",
      "swift",
      "--no-initializers",
      "--struct-or-class",
      "struct",
      "--access-level",
      "public",
      "--protocol",
      "equatable",
      "--sendable",
      "--no-date-times",
      "--alphabetize-properties",
      "--acronym-style",
      "original",
      "--telemetry",
      "disable",
      "--out",
      join(tempDir, "Protocol.swift"),
      ...sources
    ],
    { encoding: "utf8" }
  );
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(result.stderr || `quicktype exited ${result.status ?? "unknown"}`);
  }
  const generated = readFileSync(join(tempDir, "Protocol.swift"), "utf8");
  if (generated.includes(tempDir)) {
    throw new Error("quicktype embedded the temporary schema path; the Swift output would not be stable");
  }
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, finishSwift(generated));
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}

console.log(`protocol: wrote ${outputPath}`);
